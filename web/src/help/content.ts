// Раздел справки для адреса: самый длинный подходящий путь; «/» — только главная
export function sectionFor(pathname: string): HelpSection | undefined {
  return HELP.filter((s) => (s.path === "/" ? pathname === "/" : pathname === s.path || pathname.startsWith(`${s.path}/`)))
    .sort((a, b) => b.path.length - a.path.length)[0];
}

