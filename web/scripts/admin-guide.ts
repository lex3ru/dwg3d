// Инструкция администратора (8.7 п. 3) — docs/ADMIN.md из того же текста, что встроенная
// справка (src/help/content.ts), чтобы они не расходились. Запуск: npm run admin-guide.
import { writeFileSync } from "node:fs";
import { HELP, SCENARIOS } from "../src/help/content.ts";

const HEAD = `# Инструкция администратора

Как работать в системе «Планировка и учёт имущества здания» (ТЗ 8.7 п. 3). Тот же текст —
во встроенной справке: **F1** или кнопка «Справка» вверху открывает её на разделе, где вы
сейчас. Установка и обслуживание сервера — [INSTALL.md](INSTALL.md), формат полной выгрузки
— [EXPORT.md](EXPORT.md).

> Этот файл собирается из справки командой \`npm run admin-guide\` в каталоге \`web/\` — правьте
> \`web/src/help/content.ts\`, а не его.

## Роли

- **Администратор** — всё: здания и планы, каталог, расстановка, учёт имущества, проекты,
  инвентаризация, отчёты, пользователи, ссылки, журнал, настройки.
- **Просмотр** — план и расстановка выданных зданий в 2D и 3D, вещи и их карточки. Не видит
  стоимости, инвентарных номеров, документов и проектов — ни на экране, ни в ответах сервера,
  ни в выгрузках (8.4 п. 3). Ничего не меняет.
- **Гость по ссылке** — без учётной записи: план и 3D одного здания до срока ссылки.

## Первый вход

1. Откройте адрес системы, который напечатала установка, войдите как \`admin\` с временным
   паролем и придумайте свой (не короче 10 знаков).
2. «Управление › Настройки»: название учреждения (печатается на документах и наклейках), вид
   инвентарного номера, раскладка листа наклеек.
3. «Управление › Настройки › Состояние сервера» — убедитесь, что резервная копия есть.

## Как устроен экран

Слева — меню разделов и выбор здания (главная, проекты и план берут здание отсюда). Вверху —
поиск по всему (помещение, вещь, инвентарный или серийный номер, документ, тип каталога),
QR-сканер, справка и меню учётной записи (пароль, светлая или тёмная тема, выход). На
телефоне меню — вкладками внизу. Длительные операции (перевод чертежа, полная выгрузка) идут в
фоне: можно уйти с экрана, по окончании придёт сообщение.

## Каждый день

- «Главная» — что требует внимания: неисправное, в ремонте, не найденное при инвентаризации,
  неразмещённое, помещения с освещённостью ниже нормы, расхождения плана и учёта, устаревшие
  проекты. Каждый счётчик ведёт к отбору.
- Движение имущества — только документами («Склад», «Документы», карточка вещи) или переносом
  связанного предмета на плане.
- Раз в неделю — «Состояние сервера»: последняя копия не старше суток, места хватает.
`;

const ROLE = { admin: "администратор", viewer: "просмотр", guest: "гость" } as const;
const parts = [HEAD, "## По разделам\n"];
for (const s of HELP) {
  parts.push(`### ${s.title}${s.roles ? ` (${s.roles.map((r) => ROLE[r]).join(", ")})` : ""}\n\n${s.intro}\n`);
  for (const t of s.topics) {
    const who = t.roles && !(s.roles && s.roles.join() === t.roles.join()) ? ` — ${t.roles.map((r) => ROLE[r]).join(", ")}` : "";
    parts.push(`**${t.q}**${t.scenario ? ` (${t.scenario})` : ""}${who}\n\n${t.steps.map((x, i) => `${i + 1}. ${x}`).join("\n")}\n`);
  }
}
parts.push("## Сценарии\n\nСценарии ТЗ (раздел 4) и где о них сказано выше.\n");
parts.push("| № | Сценарий | Раздел |\n|---|---|---|");
for (const [code, title] of Object.entries(SCENARIOS)) {
  const where = [...new Set(HELP.filter((s) => s.topics.some((t) => (t.scenario ?? "").split(", ").includes(code))).map((s) => s.title))];
  parts.push(`| ${code} | ${title} | ${where.join(", ")} |`);
}
writeFileSync(new URL("../../docs/ADMIN.md", import.meta.url), `${parts.join("\n")}\n`);
console.log("docs/ADMIN.md готов");
